USE DATABASE WATER_LEAK_WH;
USE SCHEMA ANALYTICS;

-- For the demo, take the latest complete exported snapshot as a unit.
-- Export manifest is in S3, and snapshot completeness should be verified before loading.
CREATE OR REPLACE VIEW V_SNAPSHOT AS
SELECT MAX(PAYLOAD:exported_at::TIMESTAMP_TZ) AS EXPORTED_AT
FROM RAW_SNAPSHOT_RECORDS;

CREATE OR REPLACE VIEW V_CURRENT AS
SELECT r.PAYLOAD:dataset::STRING AS DATASET,
       r.PAYLOAD:snapshot_id::STRING AS SNAPSHOT_ID,
       r.PAYLOAD:data AS D
FROM RAW_SNAPSHOT_RECORDS r
WHERE r.PAYLOAD:exported_at::TIMESTAMP_TZ=(SELECT EXPORTED_AT FROM V_SNAPSHOT);

CREATE OR REPLACE VIEW V_CASES AS
SELECT D:case_id::NUMBER AS CASE_ID, D:source_case_id::STRING AS SOURCE_CASE_ID,
       D:zone_id::STRING AS ZONE_ID, D:case_status::STRING AS CASE_STATUS,
       D:access_status::STRING AS ACCESS_STATUS, D:risk_band::STRING AS RISK_BAND,
       TRY_TO_TIMESTAMP_NTZ(D:detected_at::STRING) AS DETECTED_AT
FROM V_CURRENT WHERE DATASET='leak_cases';

CREATE OR REPLACE VIEW V_ZONES AS
SELECT D:zone_id::STRING AS ZONE_ID, D:zone_name::STRING AS ZONE_NAME
FROM V_CURRENT WHERE DATASET='zones';

CREATE OR REPLACE VIEW V_RISK_LATEST AS
SELECT D:case_id::NUMBER AS CASE_ID, D:score::FLOAT AS RISK_SCORE,
       D:score_components AS SCORE_COMPONENTS, D:model_version::STRING AS MODEL_VERSION,
       TRY_TO_TIMESTAMP_NTZ(D:calculated_at::STRING) AS CALCULATED_AT
FROM V_CURRENT WHERE DATASET='risk_scores'
QUALIFY ROW_NUMBER() OVER (PARTITION BY CASE_ID ORDER BY CALCULATED_AT DESC,D:risk_score_id::NUMBER DESC)=1;

CREATE OR REPLACE VIEW V_WORK_ORDERS AS
SELECT D:work_order_id::NUMBER AS WORK_ORDER_ID, D:case_id::NUMBER AS CASE_ID,
       D:status::STRING AS WORK_STATUS, D:work_type::STRING AS WORK_TYPE,
       D:estimated_duration_minutes::NUMBER AS ESTIMATED_DURATION_MINUTES,
       TRY_TO_TIMESTAMP_NTZ(D:created_at::STRING) AS CREATED_AT
FROM V_CURRENT WHERE DATASET='work_orders';

CREATE OR REPLACE VIEW V_OUTCOMES AS
SELECT D:outcome_id::NUMBER AS OUTCOME_ID, D:work_order_id::NUMBER AS WORK_ORDER_ID,
       D:outcome_type::STRING AS OUTCOME_TYPE,
       D:estimated_water_loss_litres::FLOAT AS ESTIMATED_WATER_LOSS_LITRES,
       TRY_TO_TIMESTAMP_NTZ(D:inspected_at::STRING) AS INSPECTED_AT
FROM V_CURRENT WHERE DATASET='repair_outcomes';

-- Each case can have multiple work orders and outcomes. Use the LATEST conclusive outcome
-- per case to avoid inflating counts. INCONCLUSIVE is not a confirmed false alarm.
CREATE OR REPLACE VIEW V_CASE_OUTCOME_LATEST AS
SELECT w.CASE_ID, o.OUTCOME_TYPE, o.INSPECTED_AT
FROM V_OUTCOMES o JOIN V_WORK_ORDERS w ON o.WORK_ORDER_ID=w.WORK_ORDER_ID
WHERE o.OUTCOME_TYPE IN ('CONFIRMED_LEAK','NO_LEAK')
QUALIFY ROW_NUMBER() OVER(PARTITION BY w.CASE_ID ORDER BY o.INSPECTED_AT DESC,o.OUTCOME_ID DESC)=1;

CREATE OR REPLACE VIEW V_CASE_EVALUATION AS
SELECT c.CASE_ID,c.SOURCE_CASE_ID,c.ZONE_ID,COALESCE(z.ZONE_NAME,c.ZONE_ID) AS ZONE_NAME,
       c.CASE_STATUS,c.ACCESS_STATUS,c.DETECTED_AT,
       r.RISK_SCORE,r.SCORE_COMPONENTS,r.MODEL_VERSION,
       o.OUTCOME_TYPE,o.INSPECTED_AT,
       CASE WHEN o.OUTCOME_TYPE='CONFIRMED_LEAK' THEN 'CONFIRMED'
            WHEN o.OUTCOME_TYPE='NO_LEAK' THEN 'FALSE_ALARM'
            ELSE 'NOT_YET_VERIFIED' END AS EVALUATION_STATUS
FROM V_CASES c LEFT JOIN V_ZONES z ON c.ZONE_ID=z.ZONE_ID
LEFT JOIN V_RISK_LATEST r ON c.CASE_ID=r.CASE_ID
LEFT JOIN V_CASE_OUTCOME_LATEST o ON c.CASE_ID=o.CASE_ID;

CREATE OR REPLACE VIEW V_ZONE_PERFORMANCE AS
SELECT ZONE_ID,ZONE_NAME,
       COUNT(*) AS SUSPECTED_CASES,
       COUNT_IF(EVALUATION_STATUS='CONFIRMED') AS CONFIRMED_CASES,
       COUNT_IF(EVALUATION_STATUS='FALSE_ALARM') AS FALSE_ALARMS,
       COUNT_IF(EVALUATION_STATUS='NOT_YET_VERIFIED') AS UNVERIFIED_CASES,
       AVG(RISK_SCORE) AS AVG_RISK_SCORE,
       COUNT_IF(EVALUATION_STATUS='CONFIRMED') /
          NULLIF(COUNT_IF(EVALUATION_STATUS IN ('CONFIRMED','FALSE_ALARM')),0) AS CONFIRMATION_RATE_INSPECTED
FROM V_CASE_EVALUATION GROUP BY ZONE_ID,ZONE_NAME;

CREATE OR REPLACE VIEW V_REPAIR_TRENDS AS
SELECT DATE_TRUNC('MONTH',INSPECTED_AT)::DATE AS MONTH,
       COUNT_IF(OUTCOME_TYPE='CONFIRMED_LEAK') AS CONFIRMED_INSPECTIONS,
       COUNT_IF(OUTCOME_TYPE='NO_LEAK') AS NO_LEAK_INSPECTIONS,
       SUM(IFF(OUTCOME_TYPE='CONFIRMED_LEAK',ESTIMATED_WATER_LOSS_LITRES,NULL)) AS ESTIMATED_WATER_LOSS_LITRES
FROM V_OUTCOMES WHERE OUTCOME_TYPE IN ('CONFIRMED_LEAK','NO_LEAK')
GROUP BY 1;
