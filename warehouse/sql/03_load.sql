USE WAREHOUSE WATER_LEAK_COMPUTE;
USE DATABASE WATER_LEAK_WH;
USE SCHEMA ANALYTICS;
-- Loads each unique JSONL file only once into RAW_SNAPSHOT_RECORDS by Snowflake load history.
-- Do not use FORCE=TRUE: reloading identical snapshot files would duplicate raw rows.
COPY INTO RAW_SNAPSHOT_RECORDS (PAYLOAD)
 FROM (SELECT $1 FROM @WATER_LEAK_EXPORT_STAGE)
 FILE_FORMAT=(FORMAT_NAME=JSONL_FORMAT)
 PATTERN='.*[.]jsonl'
 ON_ERROR='ABORT_STATEMENT';

SELECT PAYLOAD:dataset::STRING AS DATASET, COUNT(*) AS ROWS_LOADED
FROM RAW_SNAPSHOT_RECORDS GROUP BY 1 ORDER BY 1;
