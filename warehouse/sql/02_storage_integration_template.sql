-- EDIT ALL PLACEHOLDERS. Your Snowflake role must be allowed to CREATE INTEGRATION.
-- Do not embed AWS access keys here.
CREATE STORAGE INTEGRATION IF NOT EXISTS WATER_LEAK_S3_INTEGRATION
  TYPE=EXTERNAL_STAGE STORAGE_PROVIDER=S3 ENABLED=TRUE
  STORAGE_AWS_ROLE_ARN='arn:aws:iam::<YOUR_AWS_ACCOUNT_ID>:role/<YOUR_SNOWFLAKE_S3_READ_ROLE>'
  STORAGE_ALLOWED_LOCATIONS=('s3://<YOUR_BUCKET>/warehouse/exports/');

-- Run and use STORAGE_AWS_IAM_USER_ARN and STORAGE_AWS_EXTERNAL_ID
-- to configure your AWS role's trust policy according to Snowflake instructions.
DESC INTEGRATION WATER_LEAK_S3_INTEGRATION;

USE DATABASE WATER_LEAK_WH;
USE SCHEMA ANALYTICS;
CREATE STAGE IF NOT EXISTS WATER_LEAK_EXPORT_STAGE
 URL='s3://<YOUR_BUCKET>/warehouse/exports/'
 STORAGE_INTEGRATION=WATER_LEAK_S3_INTEGRATION
 FILE_FORMAT=JSONL_FORMAT;
LIST @WATER_LEAK_EXPORT_STAGE;
